def outputs():
    entrypoint = (ROOT / "scripts/templates/entrypoint.sh").read_text()
    files = {}
    rows = []
    for version in VERSIONS:
        for variant in VARIANTS:
            suffix = "" if variant == "base" else "-" + variant
            directory = "ubuntu" + version.replace(".", "") + suffix
            links = []
            for arch in ARCHES:
                context = f"{directory}/{arch}"
                files[f"{context}/Dockerfile"] = dockerfile(version, variant, arch)
                files[f"{context}/entrypoint.sh"] = entrypoint
                files[f"{context}/README.md"] = readme(version, variant, arch, context)
                links.append(f"[{arch}]({context}/README.md)")
            rows.append(f"| {version} | {variant} | {' / '.join(links)} |")
    files["docs/matrix.md"] = "# 镜像文档索引\n\n[根 README](../README.md#镜像矩阵)\n\n| Ubuntu | 类型 | 使用文档 |\n|---|---|---|\n" + "\n".join(row.replace("](", "](../") for row in rows) + "\n"
    return files, "\n".join(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files differ")
    args = parser.parse_args()
    files, _ = outputs()
    dirty = []
    for name, content in files.items():
        path = ROOT / name
        if args.check:
            actual = path.read_text() if path.exists() else ""
            if actual != content:
                dirty.append(name)
                print("".join(difflib.unified_diff(actual.splitlines(True), content.splitlines(True), fromfile=name, tofile="generated")))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            if path.suffix == ".sh":
                path.chmod(0o755)
    if dirty:
        parser.exit(1, "Generated files are stale; run python3 scripts/generate.py\n")
    print(f"{'Checked' if args.check else 'Generated'} 24 build contexts ({len(files)} files).")


if __name__ == "__main__":
    main()
